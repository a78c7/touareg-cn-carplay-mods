# Generates dash_font.h: 8-bit coverage bitmaps for the cluster info box, four bold sizes (46 / 41 / 35 / 29 px),
# pre-rendered from Noto Sans CJK SC (SIL Open Font License 1.1).
# usage: python3 gen_dash_font.py > dash_font.h
# override font path if needed: NOTO_FONT_FMT='/path/to/NotoSansCJK-%s.ttc' python3 gen_dash_font.py > dash_font.h
import os, sys
from PIL import Image, ImageDraw, ImageFont

F = os.environ.get('NOTO_FONT_FMT', '/usr/share/fonts/opentype/noto/NotoSansCJK-%s.ttc')
_faces = {}

def face(style, px):
    k = (style, px)
    if k not in _faces:
        for idx in range(10):
            f = ImageFont.truetype(F % style, px, index=idx)
            if f.getname()[0].endswith('SC'):
                _faces[k] = f
                break
        else:
            raise SystemExit('no SC face in ' + (F % style))
    return _faces[k]

VALUE_CHARS = list('0123456789.-+:!·PRNDSMEB')
LABELS = [
    '功率', '扭矩', 'G 值', '纵向 G', '横向 G', '转速', '车速', '油门', '制动压力', '转向角', '挡位', '变速箱油温',
    '机油温度', '冷却液温度', '车外温度', '当前消耗', '燃油存量', '续驶里程'
] + [m + t for m in ('本次', '加油后', '累计') for t in ('油耗', '里程', '均速', '时长')] + [
    '0–100', '最大功率', '最大扭矩', '最大 G 值', 'Trip',
    '四轮胎压', '左前胎压', '右前胎压', '左后胎压', '右后胎压', '俯仰角', '侧倾角', '海拔'
]
UNITS = ['kW', 'Nm', 'g', 'rpm', 'km/h', '%', 'bar', '°', '°C', 'L/100km', 'km/L', 'L/h', 'L', 'km', 'm', 'h', 's']
# Tuned so 5 rows (incl. "当前消耗 88.8 L/100km") fit inside the stock 295px (x=5..300) left box at full 46px Bold digits.
SIZES = [
    ('n', 46, 24, 16),
    ('m', 41, 22, 15),
    ('c', 35, 20, 15),
    ('s', 29, 18, 14),
]

def one(f, s):
    asc, desc = f.getmetrics(); H = asc + desc
    l, t, r, b = f.getbbox(s, anchor='ls')
    adv = int(round(f.getlength(s))); x0 = min(0, l); w = max(adv, r) - x0
    im = Image.new('L', (w, H), 0)
    ImageDraw.Draw(im).text((-x0, asc), s, font=f, fill=255, anchor='ls')
    return im, w, H, asc, adv

out = sys.stdout
out.write('/* generated by gen_dash_font.py from Noto Sans CJK SC (SIL Open Font License 1.1) */\n')
out.write('typedef struct { const char *key; short w, h, base, adv; const unsigned char *bm; } dash_glyph;\n')
for sz, vpx, lpx, upx in SIZES:
    for name, style, px, items in (('val', 'Bold', vpx, VALUE_CHARS), ('lab', 'Bold', lpx, LABELS),
                                   ('unit', 'Bold', upx, UNITS)):
        entries = []
        for i, s in enumerate(items):
            im, w, H, base, adv = one(face(style, px), s)
            data = im.tobytes()
            out.write('static const unsigned char dash_%s_%s_%d[%d] = {%s};\n' % (sz, name, i, len(data), ','.join(str(v) for v in data)))
            entries.append('{"%s",%d,%d,%d,%d,dash_%s_%s_%d}' % (s, w, H, base, adv, sz, name, i))
        out.write('static const dash_glyph dash_%s_%s[%d] = {%s};\n' % (sz, name, len(entries), ',\n  '.join(entries)))
        out.write('#define DASH_%s_%s_N %d\n' % (sz.upper(), name.upper(), len(entries)))
