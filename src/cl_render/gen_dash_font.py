# Generates dash_font.h: 8-bit coverage bitmaps for the cluster info box, three sizes (normal / compact / small),
# pre-rendered from Noto Sans CJK SC (SIL Open Font License 1.1).   usage: python3 gen_dash_font.py > dash_font.h
#
# Labels with a '|' are two-line labels named like the VW board computer: the memory on top in a smaller, dimmer
# line ("自启动起" / "自上次加油起" / "累计"), the value name below ("平均消耗"). They are stored with base = -1 and
# cropped to the ink, and dash.c centres them vertically in the row.
from PIL import Image, ImageDraw, ImageFont
import sys
F = '/usr/share/fonts/opentype/noto/NotoSansCJK-%s.ttc'
_faces = {}
def face(style, px):
    k = (style, px)
    if k not in _faces:
        for idx in range(10):
            f = ImageFont.truetype(F % style, px, index=idx)
            if f.getname()[0].endswith('SC'):
                _faces[k] = f
                break
        else:
            raise SystemExit('no SC face')
    return _faces[k]

VALUE_CHARS = list('0123456789.-+:PRNDSMEB')
MEM = ['自启动起', '自上次加油起', '累计']
TRIP = ['平均消耗', '行驶里程', '平均车速', '行驶时间']
LABELS = ['功率', '扭矩', 'G 值', '纵向 G', '横向 G', '转速', '车速', '油门', '制动压力', '转向角', '挡位', '变速箱油温',
          '机油温度', '冷却液温度', '车外温度', '当前消耗', '燃油存量', '续驶里程'] + [m + t for m in ('本次', '加油后', '累计') for t in ('油耗', '里程', '均速', '时长')] + ['0–100', '最大功率', '最大扭矩', '最大 G 值', 'Trip']
UNITS = ['kW', 'Nm', 'g', 'rpm', 'km/h', '%', 'bar', '°', '°C', 'L/100km', 'km/L', 'L/h', 'L', 'km', 'h', 's']
# size: value px, label px, unit px, two-line label (top px, bottom px, gap px)
SIZES = [('n', 40, 26, 22, (18, 23, 3)), ('m', 36, 24, 20, (16, 21, 2)), ('c', 32, 22, 18, (15, 19, 2)), ('s', 26, 18, 15, (13, 15, 1))]
TOP_DIM = 0.72   # top line of a two-line label drawn at this coverage (dimmer than the value name)

def one(f, s):
    asc, desc = f.getmetrics(); H = asc + desc
    l, t, r, b = f.getbbox(s, anchor='ls')
    adv = int(round(f.getlength(s))); x0 = min(0, l); w = max(adv, r) - x0
    im = Image.new('L', (w, H), 0)
    ImageDraw.Draw(im).text((-x0, asc), s, font=f, fill=255, anchor='ls')
    return im, w, H, asc, adv

def ink_line(f, s):
    """render one line and crop it vertically to the ink"""
    im, w, H, asc, adv = one(f, s)
    bb = im.getbbox()
    top, bot = (bb[1], bb[3]) if bb else (0, H)
    return im.crop((0, top, w, bot)), adv

def two_line(top_s, bot_s, tpx, bpx, gap):
    ti, ta = ink_line(face('Regular', tpx), top_s)
    bi, ba = ink_line(face('Medium', bpx), bot_s)
    ti = ti.point(lambda v: int(v * TOP_DIM + 0.5))
    w = max(ti.width, bi.width); h = ti.height + gap + bi.height
    im = Image.new('L', (w, h), 0)
    im.paste(ti, (0, 0)); im.paste(bi, (0, ti.height + gap))
    return im, w, h, -1, max(ta, ba)

out = sys.stdout
out.write('/* generated by gen_dash_font.py from Noto Sans CJK SC (SIL Open Font License 1.1) */\n')
out.write('/* base = -1: two-line label (cropped to the ink), centred vertically in the row by dash.c */\n')
out.write('typedef struct { const char *key; short w, h, base, adv; const unsigned char *bm; } dash_glyph;\n')
for sz, vpx, lpx, upx, (tpx, bpx, gap) in SIZES:
    for name, style, px, items in (('val', 'Bold', vpx, VALUE_CHARS), ('lab', 'Medium', lpx, LABELS),
                                   ('unit', 'Regular', upx, UNITS)):
        entries = []
        for i, s in enumerate(items):
            if '|' in s:
                a, b = s.split('|')
                im, w, H, base, adv = two_line(a, b, tpx, bpx, gap)
            else:
                im, w, H, base, adv = one(face(style, px), s)
            data = im.tobytes()
            out.write('static const unsigned char dash_%s_%s_%d[%d] = {%s};\n' % (sz, name, i, len(data), ','.join(str(v) for v in data)))
            entries.append('{"%s",%d,%d,%d,%d,dash_%s_%s_%d}' % (s, w, H, base, adv, sz, name, i))
        out.write('static const dash_glyph dash_%s_%s[%d] = {%s};\n' % (sz, name, len(entries), ',\n  '.join(entries)))
        out.write('#define DASH_%s_%s_N %d\n' % (sz.upper(), name.upper(), len(entries)))
