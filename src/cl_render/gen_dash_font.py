# Generates dash_font.h: 8-bit coverage bitmaps for the cluster info box (Noto Sans CJK SC, OFL).
# usage: python3 gen_dash_font.py > dash_font.h
from PIL import Image, ImageDraw, ImageFont
import sys
F = '/usr/share/fonts/opentype/noto/NotoSansCJK-%s.ttc'
SC = 2  # face index for "SC" in the Noto CJK collection
def face(style, px):
    for idx in range(10):
        f = ImageFont.truetype(F % style, px, index=idx)
        if f.getname()[0].endswith('SC'):
            return f
    raise SystemExit('no SC face')
VAL = face('Bold', 40)
LAB = face('Medium', 26)
UNIT = face('Regular', 22)
SETS = [
    ('val', VAL, list('0123456789.-+PRNDSMEB')),
    ('lab', LAB, ['功率', '扭矩', 'G 值', '变速箱', '机油', '转速']),
    ('unit', UNIT, ['kW', 'Nm', 'g', '°C', 'rpm', 'L/100km', 'km/L', 'L/h', 'L', '%']),
]
out = sys.stdout
out.write('/* generated by gen_dash_font.py from Noto Sans CJK SC (SIL Open Font License) */\n')
out.write('typedef struct { const char *key; short w, h, base, adv; const unsigned char *bm; } dash_glyph;\n')
for name, f, items in SETS:
    asc, desc = f.getmetrics()
    H = asc + desc
    entries = []
    for i, s in enumerate(items):
        l, t, r, b = f.getbbox(s, anchor='ls')
        adv = int(round(f.getlength(s)))
        x0 = min(0, l); w = max(adv, r) - x0
        im = Image.new('L', (w, H), 0)
        ImageDraw.Draw(im).text((-x0, asc), s, font=f, fill=255, anchor='ls')
        data = im.tobytes()
        out.write('static const unsigned char dash_%s_%d[%d] = {' % (name, i, len(data)))
        out.write(','.join(str(v) for v in data))
        out.write('};\n')
        key = s.replace('\\', '\\\\').replace('"', '\\"')
        entries.append('{"%s",%d,%d,%d,%d,dash_%s_%d}' % (key, w, H, asc, adv, name, i))
    out.write('static const dash_glyph dash_%s[%d] = {%s};\n' % (name, len(entries), ',\n  '.join(entries)))
    out.write('#define DASH_%s_N %d\n#define DASH_%s_H %d\n#define DASH_%s_BASE %d\n' % (name.upper(), len(entries), name.upper(), H, name.upper(), asc))
